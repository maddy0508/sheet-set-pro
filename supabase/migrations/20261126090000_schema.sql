-- Sheet Set Pro — core schema.
-- Single business, multiple optional members. Every operational row hangs off a job,
-- which hangs off a customer, which hangs off the business.

create extension if not exists pgcrypto;

create table public.businesses (
  id uuid primary key default gen_random_uuid(),
  display_name text not null,
  legal_name text,
  abn text,
  gst_registered boolean,
  gst_rate_bp integer not null default 1000 check (gst_rate_bp between 0 and 10000),
  gst_rate_confirmed boolean not null default false,
  address text,
  email text,
  phone text,
  labour_rate_cents_per_m2 integer not null default 4500 check (labour_rate_cents_per_m2 >= 0),
  default_margin_bp integer not null default 2500 check (default_margin_bp between 0 and 10000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.members (
  business_id uuid not null references public.businesses (id) on delete cascade,
  user_id uuid not null,
  role text not null default 'owner' check (role in ('owner', 'operator')),
  created_at timestamptz not null default now(),
  primary key (business_id, user_id)
);

create table public.customers (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses (id) on delete cascade,
  name text not null check (length(btrim(name)) > 0),
  contact_name text not null default '',
  email text not null default '',
  phone text not null default '',
  address text not null default '',
  notes text not null default '',
  source_type text not null default 'REAL' check (source_type in ('REAL', 'TEST', 'SYNTHETIC')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.catalogue_profiles (
  id text primary key,
  business_id uuid not null references public.businesses (id) on delete cascade,
  manufacturer text not null,
  name text not null,
  material text not null,
  thickness_mm numeric(5, 2),
  coating text not null default '',
  effective_cover_mm integer check (effective_cover_mm is null or effective_cover_mm > 0),
  min_pitch_deg numeric(5, 2),
  max_length_mm integer,
  lap_longitudinal_mm integer,
  lap_transverse_mm integer,
  sheet_price_cents_per_m integer,
  fixing_per_sheet integer,
  flashing_girth_mm integer,
  verification_state text not null default 'PLACEHOLDER'
    check (verification_state in ('PLACEHOLDER', 'PARTIAL', 'VERIFIED')),
  price_basis text not null default 'SYNTHETIC' check (price_basis in ('SYNTHETIC', 'ENTERED')),
  source_note text not null default '',
  revision text not null default '',
  effective_from date not null default current_date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Unverified entries can never be labelled as if they carried a real specification.
  constraint catalogue_unverified_source check (
    verification_state <> 'VERIFIED' or price_basis = 'ENTERED'
  )
);

create table public.jobs (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses (id) on delete cascade,
  customer_id uuid not null references public.customers (id) on delete restrict,
  job_number text not null,
  title text not null check (length(btrim(title)) > 0),
  site_address text not null default '',
  status text not null default 'draft'
    check (status in ('draft', 'measured', 'geometry_validated', 'calculated', 'quoted', 'won', 'invoiced', 'paid', 'lost')),
  notes text not null default '',
  source_type text not null default 'REAL' check (source_type in ('REAL', 'TEST', 'SYNTHETIC')),
  profile_id text references public.catalogue_profiles (id) on delete set null,
  crs_epsg integer,
  operator_approved boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (business_id, job_number),
  unique (id, business_id)
);

-- Children carry business_id so a composite key keeps every row tied to the same
-- business as its job, without a trigger or a policy that has to trust a column.
create table public.roof_planes (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  job_id uuid not null,
  ord bigint generated by default as identity,
  ref text not null,
  x_mm integer not null,
  y_mm integer not null,
  width_mm integer not null check (width_mm > 0),
  length_mm integer not null check (length_mm > 0),
  pitch_microdeg bigint not null check (pitch_microdeg >= 0 and pitch_microdeg < 90000000),
  created_at timestamptz not null default now(),
  foreign key (job_id, business_id) references public.jobs (id, business_id) on delete cascade
);

create table public.flashings (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  job_id uuid not null,
  ord bigint generated by default as identity,
  kind text not null check (kind in ('ridge', 'hip', 'valley', 'barge', 'apron', 'box_gutter', 'eave')),
  length_mm integer not null check (length_mm >= 0),
  source text not null default 'ENTERED' check (source in ('DERIVED', 'ENTERED')),
  created_at timestamptz not null default now(),
  unique (job_id, kind),
  foreign key (job_id, business_id) references public.jobs (id, business_id) on delete cascade
);

create table public.measurement_evidence (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  job_id uuid not null,
  ord bigint generated by default as identity,
  source_kind text not null
    check (source_kind in ('manual', 'plan', 'photograph', 'aerial', 'lidar', 'ar_depth', 'ai_assisted')),
  note text not null default '',
  accuracy_claim_mm integer check (accuracy_claim_mm is null or accuracy_claim_mm >= 0),
  accuracy_basis text not null default 'unknown'
    check (accuracy_basis in ('unknown', 'operator_estimate', 'manufacturer_spec', 'verified_by_test')),
  is_verified boolean not null default false,
  created_at timestamptz not null default now(),
  foreign key (job_id, business_id) references public.jobs (id, business_id) on delete cascade
);

create table public.measurements (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  job_id uuid not null,
  ord bigint generated by default as identity,
  evidence_id uuid not null references public.measurement_evidence (id) on delete restrict,
  kind text not null
    check (kind in ('control_dimension', 'plane_width', 'plane_length', 'ridge', 'valley', 'other')),
  label text not null,
  value_mm integer not null check (value_mm > 0),
  tolerance_mm integer check (tolerance_mm is null or tolerance_mm >= 0),
  grade text not null check (grade in ('ESTIMATE_GRADE', 'ORDER_GRADE')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  foreign key (job_id, business_id) references public.jobs (id, business_id) on delete cascade
);

create table public.estimates (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  job_id uuid not null,
  revision integer not null check (revision > 0),
  lines jsonb not null check (jsonb_typeof(lines) = 'array'),
  margin_bp integer not null check (margin_bp between 0 and 10000),
  labour_cents integer not null default 0 check (labour_cents >= 0),
  totals jsonb not null check (jsonb_typeof(totals) = 'object'),
  fingerprint text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (job_id, revision),
  foreign key (job_id, business_id) references public.jobs (id, business_id) on delete cascade
);

create table public.quotes (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  job_id uuid not null,
  number text not null,
  revision integer not null check (revision > 0),
  status text not null default 'issued' check (status in ('draft', 'issued', 'accepted', 'declined')),
  lines jsonb not null check (jsonb_typeof(lines) = 'array'),
  totals jsonb not null check (jsonb_typeof(totals) = 'object'),
  gst_applied boolean not null default false,
  gst_rate_bp integer not null default 0 check (gst_rate_bp between 0 and 10000),
  issued_at timestamptz,
  valid_until date,
  fingerprint text not null,
  created_at timestamptz not null default now(),
  unique (business_id, number),
  foreign key (job_id, business_id) references public.jobs (id, business_id) on delete cascade
);

create table public.invoices (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  job_id uuid not null,
  number text not null,
  quote_id uuid,
  status text not null default 'draft' check (status in ('draft', 'issued', 'voided')),
  lines jsonb not null check (jsonb_typeof(lines) = 'array'),
  totals jsonb not null check (jsonb_typeof(totals) = 'object'),
  gst_registered_snapshot boolean,
  gst_rate_bp integer not null default 0 check (gst_rate_bp between 0 and 10000),
  issued_at timestamptz,
  due_date timestamptz,
  void_reason text,
  fingerprint text not null default '',
  created_at timestamptz not null default now(),
  unique (business_id, number),
  unique (id, business_id),
  foreign key (job_id, business_id) references public.jobs (id, business_id) on delete cascade
);

create table public.payments (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  job_id uuid not null,
  ord bigint generated by default as identity,
  amount_cents integer not null check (amount_cents > 0),
  received_at timestamptz not null,
  method text not null check (method in ('bank_transfer', 'cash', 'card', 'cheque', 'other')),
  reference text not null default '',
  idempotency_key text not null,
  created_at timestamptz not null default now(),
  unique (business_id, idempotency_key),
  unique (id, business_id),
  foreign key (job_id, business_id) references public.jobs (id, business_id) on delete cascade
);

create table public.payment_allocations (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  ord bigint generated by default as identity,
  payment_id uuid not null,
  invoice_id uuid not null,
  amount_cents integer not null check (amount_cents > 0),
  created_at timestamptz not null default now(),
  foreign key (payment_id, business_id) references public.payments (id, business_id) on delete cascade,
  foreign key (invoice_id, business_id) references public.invoices (id, business_id) on delete cascade
);

create table public.calc_snapshots (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null,
  job_id uuid not null,
  ord bigint generated by default as identity,
  input_fingerprint text not null,
  output_fingerprint text not null,
  engine_version text not null,
  total_sheets integer not null,
  total_sheet_length_mm bigint not null,
  area_mm2 bigint not null,
  blocking_issues integer not null,
  executed_in text not null check (executed_in in ('client', 'server')),
  is_authoritative boolean not null default false,
  created_at timestamptz not null default now(),
  foreign key (job_id, business_id) references public.jobs (id, business_id) on delete cascade
);

create table public.activity_events (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses (id) on delete cascade,
  at timestamptz not null default now(),
  type text not null,
  subject_type text not null
    check (subject_type in ('customer', 'job', 'estimate', 'quote', 'invoice', 'payment', 'catalogue', 'company')),
  subject_id text not null,
  detail text not null default ''
);

create index members_user_idx on public.members (user_id);
create index customers_business_idx on public.customers (business_id);
create index jobs_business_idx on public.jobs (business_id);
create index jobs_customer_idx on public.jobs (customer_id);
create index roof_planes_job_idx on public.roof_planes (job_id);
create index flashings_job_idx on public.flashings (job_id);
create index measurement_evidence_job_idx on public.measurement_evidence (job_id);
create index measurements_job_idx on public.measurements (job_id);
create index estimates_job_idx on public.estimates (job_id);
create index quotes_job_idx on public.quotes (job_id);
create index invoices_job_idx on public.invoices (job_id);
create index payments_job_idx on public.payments (job_id);
create index payment_allocations_payment_idx on public.payment_allocations (payment_id);
create index payment_allocations_invoice_idx on public.payment_allocations (invoice_id);
create index calc_snapshots_job_idx on public.calc_snapshots (job_id);
create index activity_events_business_idx on public.activity_events (business_id, at desc);
